-- Zenith Lab // Module 6 practice database: a small outdoor-gear retailer.
-- Four tables. Deliberately realistic: NULLs, cancelled orders, customers who
-- never bought anything, and orders with several line items each.

DROP TABLE IF EXISTS order_items;
DROP TABLE IF EXISTS orders;
DROP TABLE IF EXISTS products;
DROP TABLE IF EXISTS customers;

CREATE TABLE customers (
  customer_id INTEGER PRIMARY KEY,
  name        TEXT    NOT NULL,
  country     TEXT    NOT NULL,
  signup_date TEXT    NOT NULL
);
CREATE TABLE products (
  sku          TEXT PRIMARY KEY,
  product_name TEXT NOT NULL,
  category     TEXT NOT NULL,
  unit_cost    REAL NOT NULL
);
CREATE TABLE orders (
  order_id    INTEGER PRIMARY KEY,
  customer_id INTEGER NOT NULL,
  order_date  TEXT    NOT NULL,
  status      TEXT    NOT NULL,   -- completed | cancelled | refunded
  channel     TEXT                -- web | mobile | phone | NULL (not recorded)
);
CREATE TABLE order_items (
  order_item_id INTEGER PRIMARY KEY,
  order_id      INTEGER NOT NULL,
  sku           TEXT    NOT NULL,
  quantity      INTEGER NOT NULL,
  unit_price    REAL    NOT NULL
);

